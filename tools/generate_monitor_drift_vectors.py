"""Independent Fraction oracle for monitor clock ratio and declared uncertainty."""
from fractions import Fraction as F
from pathlib import Path

lines = ["// Generated by tools/generate_monitor_drift_vectors.py; GPL-3.0-only."]
for source in (8000, 44100, 48000, 96000, 384000):
    for output in (8000, 44100, 48000, 192000, 384000):
        for frequency in (48000, 10000000, 27000000):
            for cp, rp in ((-350, 250), (50, -50), (350, -250)):
                ac = round(F(source * 2) * (1 + F(cp, 1000000)))
                bc = round(F(frequency * 2) * (1 + F(rp, 1000000)))
                at, bt, u = 20000000 + 1234, 20000000 + 1765, 2000
                nominal = F(output, source)
                ratio = F(output * bc * at, frequency * bt * ac)
                low = ratio * F(at - u, at) * F(bt, bt + u)
                high = ratio * F(at + u, at) * F(bt, bt - u)
                error = max(ratio - low, high - ratio) / nominal * 1000000
                lines.append("{%d,%d,%d,%d,%d,%d,%d,%.17g,%.17g}," %
                             (source, output, frequency, ac, bc, at, bt, float(ratio), float(error)))
target = Path(__file__).resolve().parents[1] / "tests/monitor_drift_vectors.inc"
target.write_text("\n".join(lines) + "\n")
