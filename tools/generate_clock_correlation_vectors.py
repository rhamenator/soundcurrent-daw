"""Deterministic golden values from Python unbounded integers/Fraction.

No production multiplication/division code is reused. Regeneration is explicit;
C++ acceptance uses the committed table on GCC and MSVC without Python/SDK calls.
"""
from fractions import Fraction
from pathlib import Path
import random

rng = random.Random(0x5343444157)
maximum = (1 << 64) - 1
rates = [44100, 48000, 96000, 192000, 384000, 48000*8,
         (1 << 63) + 271, maximum]
rows = []
for index in range(768):
    frequency = rates[index % len(rates)]
    duration = rng.randrange(100000, 10000001)
    ticks = frequency * duration // 10000000
    p0 = rng.randrange(1, maximum - ticks + 1)
    q0 = rng.choice([rng.randrange(1, 10000000), (1 << 53) + 12345,
                     (1 << 63) + 271, maximum-100000000])
    p1, q1 = p0+ticks, q0+duration
    outside = min(ticks//100, p0-1, maximum-p1)
    position = rng.randrange(p0-outside, p1+outside+1)
    exact = Fraction(q0) + Fraction((position-p0)*duration, ticks)
    # Nearest integer QPC; an exact tie is the earlier absolute timestamp.
    shifted = exact - Fraction(1, 2)
    estimated = -((-shifted.numerator)//shifted.denominator)
    anchor_qpc = rng.choice([1, (1 << 63)+7,
                            max(1, q0+rng.randrange(-100000000, 100000001))])
    anchor_frame = rng.choice([-1000000000, -1, 0, 17, 1000000000])
    sample_rate = [44100, 48000, 96000][index % 3]
    frame = Fraction(anchor_frame) + Fraction((estimated-anchor_qpc)*sample_rate,10000000)
    floor = frame.numerator//frame.denominator
    numerator = (frame-floor)*10000000
    assert numerator.denominator == 1
    distance = max(p0-position, position-p1, 0)
    amplified = Fraction(1000*distance,ticks)
    error = 1001 + 2*(-((-amplified.numerator)//amplified.denominator))
    values = [frequency,p0,p1,q0,q1,position,anchor_qpc,anchor_frame,
              sample_rate,estimated,floor,int(numerator),error]
    rows.append('    {' + ', '.join(str(v) + ('LL' if i in [7,10] else 'ULL')
                                    for i,v in enumerate(values)) + '},')
text = '// SPDX-License-Identifier: GPL-3.0-only\n'
text += '// Generated by tools/generate_clock_correlation_vectors.py; independent Fraction oracle.\n'
text += 'constexpr Golden golden[] = {\n' + '\n'.join(rows) + '\n};\n'
Path(__file__).resolve().parents[1].joinpath('tests/clock_correlation_vectors.inc').write_text(text)
print(f'{len(rows)} deterministic exact golden vectors')
